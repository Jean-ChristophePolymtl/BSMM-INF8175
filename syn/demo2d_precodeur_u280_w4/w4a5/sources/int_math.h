// 1/sqrt(ms) : y1 en Q2.30, e2 = e/2  (ms = m·2^e, e pair)
static void rsqrt_q(ap_uint<48> ms, ap_int<34> &y1, ap_uint<6> &e2) {
#pragma HLS INLINE
    if (ms == 0) { y1 = 0; e2 = 0; return; }
    int e = 47;
    FIND_MSB_R: for (int k = 47; k >= 0; k--) {
#pragma HLS UNROLL
        if (ms[k]) { e = k; break; }
    }
    if (e & 1) e--;
    ap_uint<64> m = (e <= 30) ? ((ap_uint<64>)ms << (30 - e))
                              : ((ap_uint<64>)(ms >> (e - 30)));
    ap_int<32> d = (ap_int<32>)((m - ((ap_uint<64>)1 << 30)) >> 24);
    int idx = (int)(d / 3);
    if (idx < 0) idx = 0; if (idx > 63) idx = 63;
    ap_int<34> y0 = RSQRT_LUT[idx];
    ap_int<68> y0sq = ((ap_int<68>)y0 * y0) >> 30;
    ap_int<68> my2  = ((ap_int<68>)m * y0sq) >> 30;
    y1 = (ap_int<34>)(((ap_int<68>)y0 *
          ((((ap_int<68>)3 << 30) - my2) >> 1)) >> 30);
    e2 = (ap_uint<6>)(e >> 1);
}

// 1/v : y1 en Q.30, e  (v = m·2^e)
static void recip_q(ap_uint<40> v, ap_int<34> &y1, ap_uint<6> &e) {
#pragma HLS INLINE
    if (v == 0) { y1 = 0; e = 0; return; }
    int ee = 39;
    FIND_MSB_C: for (int k = 39; k >= 0; k--) {
#pragma HLS UNROLL
        if (v[k]) { ee = k; break; }
    }
    ap_uint<64> m = (ee <= 30) ? ((ap_uint<64>)v << (30 - ee))
                               : ((ap_uint<64>)(v >> (ee - 30)));
    int idx = (int)((m - ((ap_uint<64>)1 << 30)) >> 24);
    if (idx < 0) idx = 0; if (idx > 63) idx = 63;
    ap_int<34> y0 = RECIP_LUT[idx];
    ap_int<68> my0 = ((ap_int<68>)m * y0) >> 30;
    y1 = (ap_int<34>)(((ap_int<68>)y0 *
          (((ap_int<68>)2 << 30) - my0)) >> 30);
    e = (ap_uint<6>)ee;
}

// exp(d·C) en Q1.15, d ≤ 0, C ≈ M0s/2^SHs (Q.16 intermédiaire)
static ap_int<18> exp2_q(ap_int<40> d, int M0s, int SHs) {
#pragma HLS INLINE
    ap_int<60> prod = (ap_int<60>)d * M0s;
    ap_int<60> t16 = (SHs >= 16) ? (prod >> (SHs - 16)) : (prod << (16 - SHs));
    ap_int<44> ti = t16 >> 16;
    if (ti < -30) return 0;
    ap_uint<16> fr = (ap_uint<16>)(t16 - ((ap_int<60>)ti << 16));
    return (ap_int<18>)(EXP2_LUT[fr >> 10] >> (int)(-ti));
}
